local M = {}

local watcher

-- Where each named colour comes from when no palette has been generated:
-- the active colourscheme's highlight groups (or its terminal colours).
local fallback = {
	bg = { "Normal", "bg" },
	fg = { "Normal", "fg" },
	bg1 = { "CursorLine", "bg" },
	bg3 = { "Visual", "bg" },
	comment = { "Comment", "fg" },
	fg_dim = { "Normal", "fg" },
	brown = { "Number", "fg" },
}

local function highlight_color(group, attr)
	local value = vim.api.nvim_get_hl(0, { name = group, link = false })[attr]
	return value and string.format("#%06x", value) or nil
end

-- A value from the generated palette, for use anywhere (lualine, highlights, ...).
-- `name` is "bg" | "fg" | "bg1" | "bg3" | "comment" | "fg_dim" | "brown", or an ANSI index 0-15.
-- Without a palette it falls back to the colourscheme: g:terminal_color_N for indices,
-- highlight groups for names (nil if the colourscheme has cleared them for transparency).
function M.color(name)
	local ok, palette = pcall(require, "colourme.palette")
	if ok then
		if type(name) == "number" then
			return palette.ansi and palette.ansi[name]
		end
		return palette[name]
	end
	if type(name) == "number" then
		return vim.g["terminal_color_" .. name]
	end
	local source = fallback[name]
	return source and highlight_color(source[1], source[2]) or nil
end

-- A lualine `color` function resolving { bg, fg } on every redraw, so it follows re-renders.
-- Takes palette names/indices, e.g. pair(12, "bg"). `extra` adds fields such as gui = "bold".
function M.pair(bg, fg, extra)
	return function()
		return vim.tbl_extend("force", { bg = M.color(bg), fg = M.color(fg) }, extra or {})
	end
end

-- Re-apply the colourscheme whenever `colourme <scheme>` rewrites palette.lua.
-- The directory is watched because colourme writes atomically (temp file, then rename).
function M.watch(dir)
	if watcher then
		return
	end
	dir = dir or (vim.fn.stdpath("config") .. "/lua/colourme")
	watcher = vim.uv.new_fs_event()
	local debounce = vim.uv.new_timer()
	watcher:start(dir, {}, function(err, filename)
		if err or filename ~= "palette.lua" then
			return
		end
		debounce:stop()
		debounce:start(
			100,
			0,
			vim.schedule_wrap(function()
				-- Only follow palette changes while colourme is the active scheme.
				if vim.g.colors_name == "colourme" then
					vim.cmd.colorscheme("colourme")
				end
				pcall(function()
					require("lualine").refresh()
				end)
			end)
		)
	end)
end

-- Apply the palette generated by colourme (lua/colourme/palette.lua) through mini.base16.
function M.load()
	package.loaded["colourme.palette"] = nil
	local ok, p = pcall(require, "colourme.palette")
	if not ok then
		vim.notify("colourme: colourme.palette is missing, run `colourme <scheme>` first", vim.log.levels.WARN)
		return
	end

	local missing = vim.tbl_filter(function(key)
		return p[key] == nil
	end, {
		"bg", "fg", "bg1", "bg3", "comment", "fg_dim", "brown", "ansi",
		"fg1", "grey0", "bg5", "bg_dim", "bg_diff_red", "bg_diff_green", "bg_diff_blue",
	})
	if #missing > 0 then
		vim.notify(
			"colourme: colourme.palette is out of date (missing " .. table.concat(missing, ", ") .. "), re-run `colourme <scheme>`",
			vim.log.levels.WARN
		)
		return
	end

	local a = p.ansi
	require("mini.base16").setup({
		palette = {
			base00 = p.bg,
			base01 = p.bg1,
			base02 = p.bg3,
			base03 = p.comment,
			base04 = p.fg_dim,
			base05 = p.fg,
			base06 = p.fg,
			base07 = a[15],
			base08 = a[1],
			base09 = a[12],
			base0A = a[3],
			base0B = a[2],
			base0C = a[6],
			base0D = a[4],
			base0E = a[5],
			base0F = p.brown,
		},
		use_cterm = true,
	})

	-- Group-by-group tweaks so the result matches gruvbox-material, not just its palette.
	for group, spec in pairs(require("colourme.overrides")) do
		local hl = {}
		for key, value in pairs(spec) do
			hl[key] = (key == "fg" or key == "bg" or key == "sp") and M.color(value) or value
		end
		vim.api.nvim_set_hl(0, group, hl)
	end
	vim.g.colors_name = "colourme"
	M.watch()
end

return M
